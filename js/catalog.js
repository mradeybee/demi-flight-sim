export const INCIDENCE = 0.14

function plane(spec) {
  const stallFrac = spec.stallFrac ?? 0.38
  // Rotate must stay above stall or auto-liftoff dumps you into an instant stall.
  const rotateFrac = spec.rotateFrac ?? 0.48
  const vmax = spec.cruise * 1.12
  spec.kind = "aircraft"
  spec.flight = {
    cruise: spec.cruise,
    drag: spec.drag,
    thrust: spec.drag * vmax * vmax,
    lift: 9.81 / (INCIDENCE * spec.cruise * spec.cruise),
    mass: spec.mass,
    stall: spec.cruise * stallFrac,
    rotate: spec.cruise * rotateFrac,
    pitch: spec.pitch,
    roll: spec.roll,
    yaw: spec.yaw,
    stability: spec.stability,
  }
  return spec
}

function twin(span, y, z, r) {
  return [
    { kind: "jet", x: -span * 0.16, y, z, r, pylon: true },
    { kind: "jet", x: span * 0.16, y, z, r, pylon: true },
  ]
}

function quad(span, y, z, r) {
  return [
    { kind: "jet", x: -span * 0.14, y, z, r, pylon: true },
    { kind: "jet", x: span * 0.14, y, z, r, pylon: true },
    { kind: "jet", x: -span * 0.28, y: y + 0.15, z: z - 1.2, r, pylon: true },
    { kind: "jet", x: span * 0.28, y: y + 0.15, z: z - 1.2, r, pylon: true },
  ]
}

function props(span, y, z, r = 1.15) {
  return [
    { kind: "prop", x: -span * 0.22, y, z, r },
    { kind: "prop", x: span * 0.22, y, z, r },
  ]
}

