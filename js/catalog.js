export function partButtons(def) {
  const list = []
  if (def.gear?.mode === "retract") list.push({ group: "gear", key: "G", label: "Landing gear" })
  if (def.doorCount > 0) {
    if (def.openings === "canopy") list.push({ group: "doors", key: "O", label: "Canopy" })
    else list.push({ group: "doors", key: "O", label: "Doors" })
  }
  if (def.flaps) list.push({ group: "flaps", key: "F", label: "Flaps" })
  if (def.spoilers) list.push({ group: "spoilers", key: "P", label: "Spoilers" })
  if (def.cargo === "belly") list.push({ group: "cargo", key: "U", label: "Cargo doors" })
  if (def.cargo === "ramp") list.push({ group: "cargo", key: "U", label: "Cargo ramp" })
  if (def.droop) list.push({ group: "nose", key: "N", label: "Droop nose" })
  list.push({ group: "lights", key: "L", label: "Landing lights" })
  return list
}

export function partSummary(def) {
  return partButtons(def).map((part) => part.label).join(" · ")
}
