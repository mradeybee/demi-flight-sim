export const INCIDENCE = 0.14

function plane(spec) {
  const stallFrac = spec.stallFrac ?? 0.4
  const rotateFrac = spec.rotateFrac ?? 0.36
  const vmax = spec.cruise * 1.12
  spec.flight = {
    cruise: spec.cruise,
    drag: spec.drag,
    thrust: spec.drag * vmax * vmax,
    lift: 9.81 / (INCIDENCE * spec.cruise * spec.cruise),
    mass: spec.mass,
    stall: spec.cruise * stallFrac,
    rotate: spec.cruise * rotateFrac,
    pitch: spec.pitch,
    roll: spec.roll,
    yaw: spec.yaw,
    stability: spec.stability,
  }
  return spec
}

